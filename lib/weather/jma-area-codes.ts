/**
 * 都道府県名（と分かれば市区町村名）から気象庁の office コードを引く。
 * 未知の都道府県は null（呼び出し側は天気を出さない）。
 */
export function jmaOfficeCodeFor(
  prefecture: string | null | undefined,
  municipality?: string | null,
): string | null {
  if (!prefecture) return null;

  const base = PREFECTURE_TO_OFFICE[prefecture];
  if (!base) return null;

  if (municipality) {
    for (const { match, office } of MUNICIPALITY_TO_OFFICE) {
      if (match.test(municipality)) return office;
    }
  }
  return base;
}

/** テスト用: 対応表に載っている都道府県の一覧 */
export function supportedPrefectures(): string[] {
  return Object.keys(PREFECTURE_TO_OFFICE);
}
